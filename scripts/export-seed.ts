/**
 * Prints SQL that loads the question bank, accepted aliases and two years of daily
 * schedules into Supabase. Run with `npm run seed:sql` after editing questions.
 */
import { QUESTIONS } from '../src/core/answers';
import { dailyQuestionIds } from '../src/core/schedule';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const out: string[] = ['-- Generated by scripts/export-seed.ts. Do not edit by hand.', 'begin;'];

for (const question of QUESTIONS) {
  out.push(`insert into public.questions (id, topic, difficulty, text) values (${q(question.id)}, ${q(question.topic)}, ${question.difficulty}, ${q(question.text)}) on conflict (id) do update set topic = excluded.topic, difficulty = excluded.difficulty, text = excluded.text;`);
  for (const a of question.answers) {
    out.push(`insert into public.answers (question_id, answer_id, name, est) values (${q(question.id)}, ${q(a.id)}, ${q(a.name)}, ${a.est}) on conflict (question_id, answer_id) do update set name = excluded.name, est = excluded.est;`);
    a.keys.forEach((k, i) => {
      out.push(`insert into public.aliases (question_id, key, compact, answer_id) values (${q(question.id)}, ${q(k)}, ${q(a.compact[i])}, ${q(a.id)}) on conflict (question_id, key) do update set compact = excluded.compact, answer_id = excluded.answer_id;`);
    });
  }
}

for (let day = 1; day <= 730; day++) {
  dailyQuestionIds(day).forEach((id, pos) => {
    out.push(`insert into public.schedule (day, position, question_id) values (${day}, ${pos}, ${q(id)}) on conflict (day, position) do update set question_id = excluded.question_id;`);
  });
}

out.push('commit;');
console.log(out.join('\n'));
